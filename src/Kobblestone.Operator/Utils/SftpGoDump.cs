using System.Text.Json.Nodes;

using static Kobblestone.Operator.Entities.V1Alpha1.V1Alpha1FileBrowser;

namespace Kobblestone.Operator.Utils;

/// <summary>
/// A target as SFTPGo serves it: a local folder (a mounted volume) or an S3 bucket.
/// </summary>
public sealed record SftpGoTarget(string Name, bool ReadOnly, string? LocalPath, SftpGoS3? S3);

public sealed record SftpGoS3(string Endpoint, string Bucket, string AccessKey, string SecretKey);

/// <summary>
/// A user of the file manager, with its secrets already resolved.
/// </summary>
public sealed record SftpGoUser(
    string Name,
    string? Password,
    IReadOnlyList<string> PublicKeys,
    IList<V1Alpha1FileBrowserPermission>? Permissions);

/// <summary>
/// Renders SFTPGo's users, folders and API key as a dump for its in-memory data provider (format version 17), which it
/// loads on every start.
/// </summary>
/// <remarks>
/// With a single target, the users' home is the target. With several, the home is an empty folder and each target is a
/// virtual folder <c>/&lt;name&gt;</c> in it. Permissions in the spec are the paths users see; they are capped by the
/// targets' <c>readOnly</c> here, and read-only volumes are additionally mounted read-only.
/// </remarks>
public static class SftpGoDump
{
    /// <summary>Home of the users when there are several targets (an empty volume) or the target is in S3.</summary>
    public const string HomeDirectory = "/srv/kobblestone/home";

    /// <summary>
    /// ID of the API key. Clients send <c>X-SFTPGO-API-KEY: kobblestone.&lt;token&gt;.&lt;user&gt;</c>.
    /// </summary>
    public const string ApiKeyId = "kobblestone";

    /// <summary>
    /// SFTPGo serves its login pages only once an admin exists. The admin is never used: the admin interface is
    /// disabled, and it may only log in from inside the Pod (relevant for the REST API binding).
    /// </summary>
    public const string AdminUsername = "admin";

    /// <summary>
    /// Features of SFTPGo's web client that are turned off for all users (`filters.web_client`): the web client is only
    /// for files. No shares, 2FA, API keys, or changes of the login and profile, which are managed by the operator.
    /// </summary>
    private static readonly string[] WebClientDisabledFeatures =
    [
        "shares-disabled",
        "shares-without-password-disabled",
        "mfa-disabled",
        "password-change-disabled",
        "password-reset-disabled",
        "info-change-disabled",
        "api-key-auth-change-disabled",
        "publickey-change-disabled",
        "tls-cert-change-disabled"
    ];

    private static readonly string[] ReadOnlyPermissions = ["list", "download"];

    private static readonly string[] FullPermissions = ["*"];

    public static string Render(IReadOnlyList<SftpGoTarget> targets, IReadOnlyList<SftpGoUser> users,
        string adminPassword, string? apiToken)
    {
        var single = targets.Count == 1;

        var dump = new JsonObject
        {
            ["admins"] = new JsonArray
            {
                new JsonObject
                {
                    ["username"] = AdminUsername,
                    ["password"] = adminPassword,
                    ["status"] = 1,
                    ["permissions"] = new JsonArray("*"),
                    ["filters"] = new JsonObject { ["allow_list"] = new JsonArray("127.0.0.1/32", "::1/128") },
                    ["description"] = "Generated by Kobblestone, unused"
                }
            },
            ["folders"] = single
                ? new JsonArray()
                : new JsonArray(targets.Select(t => (JsonNode)Folder(t)).ToArray()),
            ["users"] = new JsonArray(users.Select(u => (JsonNode)User(u, targets, apiToken is not null)).ToArray()),
            ["api_keys"] = apiToken is null
                ? new JsonArray()
                : new JsonArray
                {
                    new JsonObject
                    {
                        ["id"] = ApiKeyId,
                        ["name"] = ApiKeyId,
                        // Plain, SFTPGo hashes it when loading the dump.
                        ["key"] = apiToken,
                        // User scope without a user: valid for every user, named in the key (`<id>.<token>.<user>`).
                        ["scope"] = 2,
                        ["description"] = "Generated by Kobblestone"
                    }
                },
            ["version"] = 17
        };

        return dump.ToJsonString() + "\n";
    }

    private static JsonObject User(SftpGoUser user, IReadOnlyList<SftpGoTarget> targets, bool apiEnabled)
    {
        var single = targets.Count == 1;
        var target = targets[0];

        var permissions = Permissions(targets, user.Permissions);

        var webClient = WebClientDisabledFeatures.ToList();

        if (!permissions.Values.Any(p => p.Contains("*")))
        {
            webClient.Add("write-disabled");
        }

        var json = new JsonObject
        {
            ["username"] = user.Name,
            ["status"] = 1,
            ["home_dir"] = single && target.LocalPath is { } path ? path : HomeDirectory,
            ["permissions"] = new JsonObject(permissions.Select(p =>
                new KeyValuePair<string, JsonNode?>(p.Key, new JsonArray(p.Value.Select(v => (JsonNode)v).ToArray())))),
            ["filters"] = new JsonObject
            {
                ["web_client"] = new JsonArray(webClient.Select(f => (JsonNode)f).ToArray()),
                ["allow_api_key_auth"] = apiEnabled
            },
            ["description"] = "Generated by Kobblestone"
        };

        if (user.Password is not null)
        {
            json["password"] = user.Password;
        }

        if (user.PublicKeys.Count > 0)
        {
            json["public_keys"] = new JsonArray(user.PublicKeys.Select(k => (JsonNode)k).ToArray());
        }

        if (single && target.S3 is not null)
        {
            json["filesystem"] = Filesystem(target);
        }

        if (!single)
        {
            json["virtual_folders"] = new JsonArray(targets.Select(t => (JsonNode)new JsonObject
            {
                ["name"] = t.Name, ["virtual_path"] = $"/{t.Name}"
            }).ToArray());
        }

        return json;
    }

    private static JsonObject Folder(SftpGoTarget target)
    {
        var folder = new JsonObject { ["name"] = target.Name, ["filesystem"] = Filesystem(target) };

        if (target.LocalPath is not null)
        {
            folder["mapped_path"] = target.LocalPath;
        }

        return folder;
    }

    private static JsonObject Filesystem(SftpGoTarget target) =>
        target.S3 is not { } s3
            ? new JsonObject { ["provider"] = 0 }
            : new JsonObject
            {
                ["provider"] = 1,
                ["s3config"] = new JsonObject
                {
                    ["bucket"] = s3.Bucket,
                    // S3-compatible providers mostly ignore the region, but the client needs one to sign requests.
                    ["region"] = "us-east-1",
                    ["endpoint"] = s3.Endpoint,
                    ["access_key"] = s3.AccessKey,
                    // Plain, SFTPGo encrypts it when loading the dump.
                    ["access_secret"] = new JsonObject { ["status"] = "Plain", ["payload"] = s3.SecretKey }
                }
            };

    /// <summary>
    /// Error in the permissions that the CRD schema cannot detect, or <c>null</c>.
    /// </summary>
    public static string? Validate(IReadOnlyList<SftpGoTarget> targets, SftpGoUser user)
    {
        if (targets.Count == 1)
        {
            return null;
        }

        var unknown = user.Permissions?
            .Select(p => Normalize(p.Path))
            .FirstOrDefault(p => p != "/" && TargetOf(targets, p) is null);

        return unknown is null
            ? null
            : $"User {user.Name} has permissions for {unknown}, which is not in a target. With several targets, paths start with the target's folder, e.g. /{targets[0].Name}.";
    }

    /// <summary>
    /// SFTPGo permissions (path → permissions) of a user. SFTPGo applies the permissions of the most specific path, so
    /// every path the spec names gets its own entry, capped by the target it belongs to.
    /// </summary>
    public static Dictionary<string, string[]> Permissions(IReadOnlyList<SftpGoTarget> targets,
        IList<V1Alpha1FileBrowserPermission>? permissions)
    {
        var entries = (permissions ?? [])
            .Select(p => (Path: Normalize(p.Path), p.Access))
            .GroupBy(p => p.Path)
            .ToDictionary(g => g.Key, g => g.Last().Access);

        // Default: full access, limited by the targets.
        var rootAccess = entries.GetValueOrDefault("/", FileBrowserAccess.ReadWrite);

        var result = new Dictionary<string, string[]>();

        if (targets.Count == 1)
        {
            var target = targets[0];

            result["/"] = ToPermissions(Cap(rootAccess, target));

            foreach (var (path, access) in entries.Where(e => e.Key != "/"))
            {
                result[path] = ToPermissions(Cap(access, target));
            }

            return result;
        }

        // The home only contains the target folders.
        result["/"] = ["list"];

        foreach (var target in targets)
        {
            var targetPath = $"/{target.Name}";

            result[targetPath] = ToPermissions(Cap(entries.GetValueOrDefault(targetPath, rootAccess), target));
        }

        foreach (var (path, access) in entries.Where(e => e.Key != "/"))
        {
            if (TargetOf(targets, path) is { } target && path != $"/{target.Name}")
            {
                result[path] = ToPermissions(Cap(access, target));
            }
        }

        return result;
    }

    private static SftpGoTarget? TargetOf(IReadOnlyList<SftpGoTarget> targets, string path) =>
        targets.FirstOrDefault(t => path == $"/{t.Name}" || path.StartsWith($"/{t.Name}/", StringComparison.Ordinal));

    private static FileBrowserAccess Cap(FileBrowserAccess access, SftpGoTarget target) =>
        target.ReadOnly && access is FileBrowserAccess.ReadWrite ? FileBrowserAccess.ReadOnly : access;

    private static string[] ToPermissions(FileBrowserAccess access) => access switch
    {
        FileBrowserAccess.ReadWrite => FullPermissions,
        FileBrowserAccess.ReadOnly => ReadOnlyPermissions,
        _ => []
    };

    private static string Normalize(string path)
    {
        var segments = path.Split('/', StringSplitOptions.RemoveEmptyEntries);

        return "/" + string.Join('/', segments);
    }
}
