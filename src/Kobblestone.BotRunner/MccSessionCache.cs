using System.Globalization;
using System.Text;

using Kobblestone.Sessions;

using MessagePack;

namespace Kobblestone.BotRunner;

/// <summary>
/// Converts a standard <see cref="MinecraftSession"/> into the cache files of the bundled MCC version, so MCC starts
/// already logged in. This is the only place that knows MCC's cache formats; it has to match the MCC version of the
/// image.
/// </summary>
public static class MccSessionCache
{
    /// <summary>MessagePack <c>Dictionary&lt;string, SessionToken&gt;</c>, keyed by the lower-case login.</summary>
    private const string SessionCacheFile = "SessionCache.db";

    /// <summary>Plain text, one <c>login=publicKey,signature,signatureV2,privateKey,expiresAt,refreshAfter</c> per line.</summary>
    private const string ProfileKeyCacheFile = "ProfileKeyCache.ini";

    private const string MccDateFormat = "yyyy-MM-ddTHH:mm:ss.ffffffZ";

    public static void Write(string workingDirectory, string login, MinecraftSession session)
    {
        var key = login.ToLowerInvariant();

        // The refresh token is deliberately not handed to MCC: the `Account` owns refreshing. The bot is restarted
        // with the new session when the `Account` refreshed it.
        var cache = new Dictionary<string, MccSessionToken>
        {
            [key] = new()
            {
                ID = session.AccessToken,
                PlayerName = session.Username,
                PlayerID = session.Uuid.ToString("N"),
                ClientID = Guid.NewGuid().ToString("N"),
                RefreshToken = string.Empty,
                ServerIDhash = string.Empty,
                ServerPublicKey = null
            }
        };

        File.WriteAllBytes(Path.Combine(workingDirectory, SessionCacheFile), MessagePackSerializer.Serialize(cache));

        var profileKeyPath = Path.Combine(workingDirectory, ProfileKeyCacheFile);

        if (session.ProfileKey is not { } profileKey)
        {
            File.Delete(profileKeyPath);

            return;
        }

        var signatureV2 = profileKey.PublicKeySignatureV2;
        var signature = profileKey.PublicKeySignature ?? signatureV2;

        var line = string.Join(',',
            PemBody(profileKey.PublicKeyPem),
            signature,
            signatureV2,
            PemBody(profileKey.PrivateKeyPem),
            profileKey.ExpiresAt.UtcDateTime.ToString(MccDateFormat, CultureInfo.InvariantCulture),
            profileKey.RefreshedAfter.UtcDateTime.ToString(MccDateFormat, CultureInfo.InvariantCulture));

        File.WriteAllLines(profileKeyPath,
        [
            "# Generated by Kobblestone.BotRunner",
            "# Login=PublicKey(base64),PublicKeySignature(base64),PublicKeySignatureV2(base64),PrivateKey(base64),ExpiresAt,RefreshAfter",
            $"{key}={line}"
        ]);
    }

    /// <summary>
    /// Base64 body of a PEM document (the DER bytes MCC expects), without armor and line breaks.
    /// </summary>
    private static string PemBody(string pem)
    {
        var body = new StringBuilder();

        foreach (var line in pem.Split('\n'))
        {
            var trimmed = line.Trim();

            if (trimmed.Length > 0 && !trimmed.StartsWith("-----", StringComparison.Ordinal))
            {
                body.Append(trimmed);
            }
        }

        return body.ToString();
    }
}

/// <summary>
/// Mirror of MCC's <c>MinecraftClient.Protocol.Session.SessionToken</c> (MessagePack keys 0-6).
/// </summary>
[MessagePackObject]
public sealed class MccSessionToken
{
    [Key(0)] public string ID { get; set; } = string.Empty;

    [Key(1)] public string PlayerName { get; set; } = string.Empty;

    [Key(2)] public string PlayerID { get; set; } = string.Empty;

    [Key(3)] public string ClientID { get; set; } = string.Empty;

    [Key(4)] public string RefreshToken { get; set; } = string.Empty;

    [Key(5)] public string ServerIDhash { get; set; } = string.Empty;

    [Key(6)] public byte[]? ServerPublicKey { get; set; }
}
